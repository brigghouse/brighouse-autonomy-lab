"""Build results/README.md from every results/*/summary.json."""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RES = REPO / "results"

HEADER = """# Results

Generated by `scripts/make_results_table.py` from the `summary.json` file of each run. Raw mavaudit
reports (`*.json`, `*.md`) and simulator logs are in each subfolder. All runs are local
software-in-the-loop simulations on 127.0.0.1.

**Columns.** *signed* = frames sent by the vehicle that carried a MAVLink 2 signature.
*Unsigned request answered* = the vehicle replied to mavaudit's unsigned, read-only parameter
request. *FTP advertised* = from `AUTOPILOT_VERSION`; *unknown* when the vehicle ignored the unsigned
request for it. *Keyed check* = frames whose signature verified with the lab key (decoded frames only).
**E2/E4** = the same audit repeated after the defender provisioning step (an unsigned `SETUP_SIGNING` with the
lab key over the local link). On a stack without signing support the step has no effect.

"""


def fmt_keyed(k):
    if not k:
        return "-"
    total = k.get("frames_decoded", k.get("frames"))
    return f"{k['valid_signatures']}/{total}"


def main():
    rows = []
    notes = []
    for summary in sorted(RES.glob("*/summary.json")):
        s = json.loads(summary.read_text())
        folder = summary.parent.name
        for run, r in s["runs"].items():
            rows.append(
                f"| [{folder}]({folder}/) | {s['source_rev']} | {run} | {r['frames']} | "
                f"{r['signed_frames']} | {'yes' if r['unsigned_probe_answered'] else 'no'} | "
                f"{'yes' if r['ftp_advertised'] else ('no' if r['ftp_advertised'] is False else 'unknown')} | "
                f"{fmt_keyed(r.get('keyed_check'))} | {', '.join(r['findings'])} |"
            )
        extra = {k: v for k, v in s.items() if k not in ("runs", "stack", "source_rev", "started_utc")}
        if extra:
            notes.append(f"- **{folder}** ({s['stack']}, {s['started_utc']}): `{json.dumps(extra)}`")
    table = [
        "| Run folder | Source | Experiment | Frames | Signed | Unsigned request answered | FTP advertised | Keyed check | Findings |",
        "|---|---|---|---|---|---|---|---|---|",
        *rows,
    ]
    text = HEADER + "\n".join(table) + "\n"
    if notes:
        text += "\n## Extra measurements\n\n" + "\n".join(notes) + "\n"
    text += "\nFinding IDs are described in [docs/findings.md](../docs/findings.md).\n"
    (RES / "README.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
