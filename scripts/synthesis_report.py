"""Regenerate results/model/synthesis.json and SYNTHESIS.md from the model.

Previously SYNTHESIS.md was written by hand, which is exactly how a prose artefact drifts
from the code that produced it. This script writes both from one call to `analyse()`.

    python scripts/synthesis_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from mavaudit.model.synthesis import EDITS, analyse  # noqa: E402

HEADER = """# Design-space synthesis: greedy-minimal liveness-preserving remediations

Generated by `scripts/synthesis_report.py` from `mavaudit.model.synthesis.analyse()`.
Do not edit by hand.

For each measured or reference policy: the witnessed properties, whether the policy is
functional (liveness), and the **greedy-minimal** set of single-parameter edits that clears
all safety failures (P1-P3) while keeping the vehicle functional. Greedy is not guaranteed
globally minimal. Edits that are a no-op for a policy are never counted, and an edit is
added only when it strictly reduces the failure count. Where several edits are equally good
at a step, all of them are listed as alternatives, and the first in a fixed order is taken
so the result is deterministic.

Available edits: {edits}.
"""


def main():
    data = analyse()
    out = REPO / "results" / "model"
    out.mkdir(parents=True, exist_ok=True)
    (out / "synthesis.json").write_text(json.dumps(data, indent=2) + "\n")

    lines = [HEADER.format(edits=", ".join(f"`{e}`" for e in EDITS)), "",
             "| Policy | Failures | Functional | Greedy-minimal edits | Alternatives | Residual |",
             "|---|---|---|---|---|---|"]
    for name, r in data.items():
        combo = r["min_edits_to_clear_failures"]
        alts = r.get("min_edits_alternatives") or []
        if combo:
            combo_s = " + ".join(f"`{c}`" for c in combo)
            alt_s = "; ".join(", ".join(f"`{a}`" for a in step) for step in alts if len(step) > 1) or "—"
        else:
            combo_s = ("none needed" if not r["failures"]
                       else "none: no single edit reduces failures (adopt the full mechanism)")
            alt_s = "—"
        lines.append(f"| `{name}` | {', '.join(r['failures']) or '—'} | "
                     f"{'yes' if r['functional'] else 'no'} | {combo_s} | {alt_s} | "
                     f"{', '.join(r['residual_failures_after_combo']) or '—'} |")
    (out / "SYNTHESIS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[2:]))


if __name__ == "__main__":
    main()
