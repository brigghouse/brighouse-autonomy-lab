"""Write results/<campaign>/README.md from that campaign's summary.json.

Hand-written campaign READMEs drift from the JSON beside them. These are generated,
so a figure in the prose cannot disagree with the record. Re-run after any campaign.

    python scripts/results_readme.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"


def render(name: str, s: dict) -> str:
    runs = s.get("runs", {})
    L = [f"# {name}", ""]
    L.append(f"Stack: **{s.get('stack', 'unknown')}**  ")
    L.append(f"Source revision: `{s.get('source_rev', 'unrecorded')}`  ")
    L.append(f"Started: {s.get('started_utc', 'unrecorded')}")
    L += ["", "Generated by `scripts/results_readme.py` from `summary.json` in this",
          "directory. Edit the campaign, not this file.", "",
          "| run | frames | signed | v1 | unsigned probe answered | FTP advertised | findings |",
          "|---|---:|---:|---:|---|---|---|"]
    for rn, r in runs.items():
        ans = r.get("unsigned_probe_answered")
        ftp = r.get("ftp_advertised")
        fmt = lambda v: "—" if v is None else ("yes" if v else "no")
        L.append(f"| `{rn}` | {r.get('frames','—')} | {r.get('signed_frames','—')} | "
                 f"{r.get('v1_frames','—')} | {fmt(ans)} | {fmt(ftp)} | "
                 f"{', '.join(r.get('findings', [])) or '—'} |")

    keyed = {rn: r["keyed_check"] for rn, r in runs.items() if r.get("keyed_check")}
    if keyed:
        L += ["", "## Signature verification with the key",
              "", "| run | frames decoded | valid signatures | unknown msgid skipped |",
              "|---|---:|---:|---:|"]
        for rn, k in keyed.items():
            L.append(f"| `{rn}` | {k.get('frames_decoded','—')} | "
                     f"{k.get('valid_signatures','—')} | "
                     f"{k.get('unknown_msgid_frames_skipped','—')} |")

    L += ["", "## What this campaign does not establish", "",
          "These runs were taken against a simulated vehicle on the host, over the",
          "transports named in the run labels. They say what this build did on these",
          "links on this date. They do not establish behaviour on flight hardware, on",
          "other transports, or in other builds of the same version. A run that records",
          "no answer is a run in which nothing answered, which is not the same as a",
          "refusal unless the campaign carried a positive control.", ""]
    if s.get("note"):
        L += [f"> {s['note']}", ""]
    return "\n".join(L)


def main() -> int:
    wrote = []
    for d in sorted(RESULTS.iterdir()):
        sm = d / "summary.json"
        if not d.is_dir() or not sm.exists():
            continue
        s = json.loads(sm.read_text())
        if "runs" not in s:
            continue
        target = d / "README.md"
        # Never clobber a hand-written README. Only a file this script wrote carries
        # the marker, so an existing one without it is somebody's prose.
        if target.exists() and "scripts/results_readme.py" not in target.read_text():
            print(f"skip {d.name}: README.md is hand-written")
            continue
        target.write_text(render(d.name, s))
        wrote.append(d.name)
    print("wrote README.md in:", ", ".join(wrote) or "(none)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
