"""Render the exploration results to JSON and a Markdown property matrix."""

from __future__ import annotations

import json
from pathlib import Path

from .configs import ALL
from .explore import run_all
from .semantics import Policy

PROP_NAMES = {
    "P1": "command-integrity (A-command accepted off trusted link)",
    "P2": "key-integrity (A changes V's key)",
    "P3": "replay-resistance (accepted command replayed)",
    "P4": "first-use window (A installs key before provisioning)",
    "P5": "trusted-link exemption (A-command accepted on trusted link)",
    "P6": "key exposure (A on provisioning link forges after key leak)",
}
# P1,P2,P3 are security FAILURES (X is bad). P4,P5,P6 are exposure facts (X = present).
FAILURE_PROPS = ("P1", "P2", "P3")


def policy_table() -> str:
    rows = ["| Policy | trusted links | unsigned allow-list | TOFU | unsigned re-key (trusted) | signed re-key | setup refused armed |",
            "|---|---|---|---|---|---|---|"]
    for p in ALL:
        rows.append(f"| `{p.name}` | {sorted(p.trusted) or '—'} | {sorted(p.allow_unsigned)} | "
                    f"{'yes' if p.tofu else 'no'} | {'yes' if p.unsigned_rekey_on_trusted else 'no'} | "
                    f"{'yes' if p.signed_rekey else 'no'} | {'yes' if p.refuse_setup_armed else 'no'} |")
    return "\n".join(rows)


def build(depth: int = 3) -> dict:
    rows = run_all(ALL, depth=depth)
    return {"depth": depth, "properties": PROP_NAMES, "rows": rows}


def to_markdown(data: dict) -> str:
    out = ["# Formal model: acceptance semantics and bounded adversary exploration", "",
           "Generated by `python -m mavaudit.model.report`. Each row is a (policy, scenario) pair; "
           "a cell is `X` when the property's condition is witnessed within the search depth "
           f"({data['depth']}). P1-P3 are security failures (X is bad); P4-P6 are exposure facts.",
           "", "## Policies", "", policy_table(), "", "## Properties", ""]
    for k, v in data["properties"].items():
        out.append(f"- **{k}** — {v}")
    out += ["", "## Results", "",
            "| Policy | Scenario | P1 | P2 | P3 | P4 | P5 | P6 |", "|---|---|---|---|---|---|---|---|"]
    for r in data["rows"]:
        cells = " | ".join("X" if r[p] else "·" for p in ("P1", "P2", "P3", "P4", "P5", "P6"))
        out.append(f"| `{r['policy']}` | {r['scenario']} | {cells} |")
    out += ["", "## Shortest witnesses (selected)", ""]
    for r in data["rows"]:
        for p, w in r["witnesses"].items():
            if w:
                out.append(f"- `{r['policy']}` / {r['scenario']} / **{p}**:")
                out.append(f"  - " + "\n  - ".join(w))
    out.append("")
    return "\n".join(out)


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("results/model"))
    ap.add_argument("--depth", type=int, default=3)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    data = build(a.depth)
    (a.out / "model-results.json").write_text(json.dumps(data, indent=2, default=str))
    (a.out / "README.md").write_text(to_markdown(data))
    print(to_markdown(data))


if __name__ == "__main__":
    main()
